/*
 * Типографика неразрывных пробелов — DESIGN.md §2, подраздел «Неразрывные
 * пробелы» (решение архитектора 02.09.2026). Одна чистая функция, без внешних
 * зависимостей (§1: библиотеки не подключаются).
 *
 * Заменяет ОБЫЧНЫЙ пробел (U+0020) на неразрывный (U+00A0) в перечисленных
 * местах. Ничего не переносит, слов не меняет — правило типографическое.
 *
 * Идемпотентна: работает только по U+0020, а после первого прохода в этих
 * местах уже U+00A0, поэтому повторный вызов ничего не трогает. Проверки
 * «слева граница слова» — через lookbehind нулевой ширины: соседние короткие
 * слова («а не на одной») склеиваются за один проход, без второго вызова.
 */

const NBSP = ' ';

// Однобуквенные и двухбуквенные предлоги и союзы — список из DESIGN.md §2.
const SHORT = 'в|во|и|к|на|о|об|от|по|с|со|у|за|из|до|а|но|не|ни|то|же|бы|ли';

// Сокращения с точкой — закрытый список из брифа P12-R2 §3.1.
const ABBR = 'г|ул|стр';

// Тире, которое не должно начинать строку: длинное (—) из брифа §3.1
// и короткое (–), которым размечены строки данных («Прямые – Автоклуб 888»).
const DASH = '[—–]';

export function typo(text: string): string {
	if (!text) return text;

	return text
		// 1. Короткий предлог/союз + следующее слово. Слева — начало строки
		//    или не-буква; справа — обычный пробел и затем буква/цифра
		//    (возможная открывающая кавычка или скобка между ними допускается).
		//    Регистронезависимо, только когда слово стоит отдельно.
		.replace(
			new RegExp(`(?<=^|[^\\p{L}])(${SHORT})\\u0020(?=[«"'(]?[\\p{L}\\d])`, 'giu'),
			`$1${NBSP}`,
		)
		// 2. Число + следующее слово («8 интервью», «3 года»).
		.replace(/(?<=\d) (?=\p{L})/gu, NBSP)
		// 3. Сокращение с точкой + слово или число («г. Владивосток», «стр. 5»).
		.replace(
			new RegExp(`(?<=(?:^|[^\\p{L}])(?:${ABBR}))\\.\\u0020(?=[\\p{L}\\d])`, 'giu'),
			`.${NBSP}`,
		)
		// 3b. Инициал — одна заглавная буква с точкой + слово («А. С. Пушкин»).
		//     DESIGN.md §2: «инициалы и сокращения с именем».
		.replace(/(?<=(?:^|[^\p{L}])\p{Lu})\. (?=\p{L})/gu, `.${NBSP}`)
		// 4. Тире не начинает строку — склеивается с предшествующим словом.
		.replace(new RegExp(`(?<=\\S)\\u0020(?=${DASH})`, 'gu'), NBSP);
}
